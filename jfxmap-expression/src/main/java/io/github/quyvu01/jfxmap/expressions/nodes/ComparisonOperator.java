package io.github.quyvu01.jfxmap.expressions.nodes;

/**
 * The comparison operators.
 */
public enum ComparisonOperator {
    EQUAL,                 // =
    NOT_EQUAL,             // !=
    GREATER_THAN,          // >
    LESS_THAN,             // <
    GREATER_THAN_OR_EQUAL, // >=
    LESS_THAN_OR_EQUAL,    // <=
    CONTAINS,              // contains
    STARTS_WITH,           // startswith
    ENDS_WITH              // endswith
}
